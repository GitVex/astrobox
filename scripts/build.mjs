#!/usr/bin/env node
/* Astrobox build: src/ -> dist/ (and a copy in docs/assets for the GitHub Pages site).
   Generates the token CSS and JSON from src/tokens.config.mjs and src/palette.js,
   injects the palette into the runtime, and stamps the version from package.json. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import C from '../src/tokens.config.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const wr = (p, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true }); fs.writeFileSync(path.join(ROOT, p), s); };
const VERSION = JSON.parse(rd('package.json')).version;

/* palette functions, shared with the runtime */
const paletteSrc = rd('src/palette.js');
const { gen } = new Function(paletteSrc + '\nreturn { gen, block };')();

const cfg = C.accent;
const modes = { night: gen(false, false, cfg), 'night-high': gen(false, true, cfg), day: gen(true, false, cfg), 'day-high': gen(true, true, cfg) };
const blk = t => Object.keys(t).filter(k => k[0] === '-').map(k => '  ' + k + ': ' + t[k] + ';').join('\n');
const kv = (o, p) => Object.entries(o).map(([k, v]) => '  --' + (p || '') + k + ': ' + v + ';').join('\n');
const FONTS = C.fonts, FS = C.sizes, STRUCT = C.structure, MOTION = C.motion, DENSITY = C.density, STATIC = C.imageOverlay;

const css = `/*!
 * Astrobox tokens ${VERSION}
 * Generated by scripts/build.mjs from src/tokens.config.mjs. Do not edit by hand. Default accent: signal brass ${cfg.acc}.
 * Four colour modes: night (default), night high contrast, day, day high contrast.
 *   Theme:     data-theme="light" | "dark" on <html>; unset follows the system setting.
 *   Contrast:  data-contrast="high" on <html>.
 *   Voice:     data-voice="mechanical" | "prose" on a screen or container.
 * To use another accent at runtime, call Astrobox.palette.apply({ acc: '#rrggbb' }).
 */
@import url('${C.fontsUrl}');

@layer astrobox {
/* ---------- colour: night (default) ---------- */
:root {
${blk(modes.night)}
${kv(STATIC).replace(/  --/g, '  --')}
  color-scheme: dark;
}
/* ---------- colour: night, high contrast ---------- */
:root[data-contrast="high"] {
${blk(modes['night-high'])}
  --under-img: rgba(0,0,0,.75);
  --scrim: rgba(0,0,0,.9);
}
/* ---------- colour: day ---------- */
@media (prefers-color-scheme: light) {
 :root:not([data-theme="dark"]) {
${blk(modes.day)}
  color-scheme: light;
 }
}
:root[data-theme="light"] {
${blk(modes.day)}
  color-scheme: light;
}
/* ---------- colour: day, high contrast ---------- */
@media (prefers-color-scheme: light) {
 :root[data-contrast="high"]:not([data-theme="dark"]) {
${blk(modes['day-high'])}
 }
}
:root[data-contrast="high"][data-theme="light"] {
${blk(modes['day-high'])}
}

/* ---------- type ---------- */
:root {
  --fd: ${FONTS.display};
  --fb: ${FONTS.body};
  --fm: ${FONTS.mono};
${kv(FS, 'fs-')}
}
/* ---------- structure ---------- */
:root {
${kv(STRUCT)}
}
/* ---------- motion (prose tempo is the default) ---------- */
:root {
${kv(MOTION.prose)}
${kv(MOTION.shared)}
}
[data-voice="mechanical"] {
${kv(MOTION.mechanical)}
${kv(DENSITY.mechanical)}
}
[data-voice="prose"] {
${kv(MOTION.prose)}
${kv(DENSITY.prose)}
}
}
`;
/* ---------- W3C design tokens (DTCG) ---------- */
const toHex = v => {
 if (v[0] === '#') return v;
 const m = v.match(/rgba\((\d+),(\d+),(\d+),([\d.]+)\)/);
 return '#' + [m[1], m[2], m[3]].map(x => (+x).toString(16).padStart(2, '0')).join('') + Math.round(+m[4] * 255).toString(16).padStart(2, '0');
};

const colour = {};
for (const [mode, t] of Object.entries(modes)) {
 colour[mode] = {};
 for (const k of Object.keys(t).filter(k => k[0] === '-')) colour[mode][k.slice(2)] = { $type: 'color', $value: toHex(t[k]), $description: C.roles[k] || '' };
}
const bez = s => s.match(/[\d.]+/g).map(Number);
const dur = v => ({ $type: 'duration', $value: v });
const json = {
 $description: 'Astrobox design tokens '+VERSION+', generated by scripts/build.mjs. Default accent ' + cfg.acc + '.',
 color: colour,
 font: { family: Object.fromEntries(Object.entries(FONTS).map(([k, v]) => [k, { $type: 'fontFamily', $value: v.split(',').map(x => x.trim().replace(/'/g, '')) }])),
  size: Object.fromEntries(Object.entries(FS).map(([k, v]) => [k, { $type: 'dimension', $value: v }])) },
 structure: Object.fromEntries(Object.entries(STRUCT).map(([k, v]) => [k, { $type: 'dimension', $value: v }])),
 density: Object.fromEntries(Object.entries(DENSITY).map(([voice, o]) => [voice, Object.fromEntries(Object.entries(o).map(([k, v]) => [k, { $type: 'dimension', $value: v }]))])),
 motion: Object.fromEntries(['prose', 'mechanical'].map(voice => [voice, Object.fromEntries(Object.entries(MOTION[voice]).map(([k, v]) => [k, k === 'ease' ? { $type: 'cubicBezier', $value: bez(v) } : dur(v)]))]).concat([['shared', Object.fromEntries(Object.entries(MOTION.shared).map(([k, v]) => [k, k === 'ease-pop' ? { $type: 'cubicBezier', $value: bez(v) } : dur(v)]))]])),
 accent: { presets: Object.fromEntries(Object.entries(C.presets).map(([k, v]) => [k, { $type: 'color', $value: v }])) }
};

wr('dist/astrobox.tokens.css', css);
wr('dist/astrobox.tokens.json', JSON.stringify(json, null, 2) + '\n');

/* runtime: inject the palette and the version */
/* drop the two-line file header, indent one space to match the runtime */
const indented = paletteSrc.split('\n').slice(2).map(l => l ? ' ' + l : l).join('\n');
let runtime = rd('src/runtime.js');
if (!runtime.includes('@@PALETTE@@')) throw new Error('runtime is missing the @@PALETTE@@ marker');
runtime = runtime.replace(/^.*@@PALETTE@@.*$/m, indented.trimEnd()).replace("version: '1.0.0'", "version: '" + VERSION + "'").replace('Astrobox runtime 1.0', 'Astrobox runtime ' + VERSION);
wr('dist/astrobox.js', runtime);

/* components */
wr('dist/astrobox.css', rd('src/components.css').replace('Astrobox components 1.0', 'Astrobox components ' + VERSION));

/* the Pages site loads the same files */
for (const f of ['astrobox.tokens.css', 'astrobox.css', 'astrobox.js', 'astrobox.tokens.json']) wr('docs/assets/' + f, rd('dist/' + f));
console.log('Astrobox ' + VERSION + ' built: dist/ and docs/assets/ updated.');
